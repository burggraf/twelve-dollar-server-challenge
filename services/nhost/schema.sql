-- Application data only; Nhost Auth/platform schemas and retained probe evidence stay untouched.
-- Native SQL functions are called ONLY through the packaged GraphQL API in serving traffic.
BEGIN;
CREATE SCHEMA feed_data;
CREATE SCHEMA feed_api;
REVOKE ALL ON SCHEMA feed_data,feed_api FROM PUBLIC;
-- Match the existing PostgreSQL bytea model: TEXT/JSONB cannot hold body U+0000.
CREATE FUNCTION feed_data.codepoints(value bytea) RETURNS bigint
 LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE SET search_path=pg_catalog AS $$
 SELECT count(*) FROM generate_series(0,octet_length(value)-1) n WHERE (get_byte(value,n)&192)<>128
$$;
CREATE TABLE feed_data.users (
 id bigint PRIMARY KEY,username text COLLATE "C" NOT NULL UNIQUE,
 created_at text COLLATE "C" NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);
CREATE TABLE feed_data.posts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES feed_data.users(id),
 body bytea NOT NULL CHECK(feed_data.codepoints(body) BETWEEN 1 AND 500),
 created_at text COLLATE "C" NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);
CREATE TABLE feed_data.likes (
 user_id bigint NOT NULL REFERENCES feed_data.users(id),post_id bigint NOT NULL REFERENCES feed_data.posts(id),
 created_at text COLLATE "C" NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
 PRIMARY KEY(user_id,post_id)
);
CREATE INDEX posts_created_at_id_idx ON feed_data.posts(created_at DESC,id DESC);
CREATE INDEX posts_user_id_idx ON feed_data.posts(user_id);
CREATE INDEX likes_post_id_idx ON feed_data.likes(post_id);
-- Hasura's documented empty return-shape table; NEVER stores cached/application results.
CREATE TABLE feed_api.result(payload jsonb);
CREATE FUNCTION feed_data.post_json(p_id bigint) RETURNS jsonb LANGUAGE sql STABLE
 SET search_path=pg_catalog,feed_data AS $$
 SELECT jsonb_build_object('id',p.id::text,'body_b64',encode(p.body,'base64'),'created_at',p.created_at,'author',u.username,
  'like_count',(SELECT count(*)::text FROM feed_data.likes l WHERE l.post_id=p.id))
 FROM feed_data.posts p JOIN feed_data.users u ON u.id=p.user_id WHERE p.id=p_id
$$;
CREATE FUNCTION public.nhost_health() RETURNS SETOF feed_api.result LANGUAGE plpgsql STABLE
 SET search_path=pg_catalog,feed_data AS $$
 BEGIN PERFORM 1 FROM feed_data.users LIMIT 1; RETURN QUERY SELECT 'true'::jsonb; END
$$;
CREATE FUNCTION public.nhost_feed() RETURNS SETOF feed_api.result LANGUAGE sql STABLE
 SET search_path=pg_catalog,feed_data AS $$
 SELECT coalesce(jsonb_agg(feed_data.post_json(p.id) ORDER BY p.created_at DESC,p.id DESC),'[]'::jsonb)
 FROM (SELECT p.id,p.created_at FROM feed_data.posts p JOIN feed_data.users u ON u.id=p.user_id
  ORDER BY p.created_at DESC,p.id DESC LIMIT 20) p
$$;
CREATE FUNCTION public.nhost_detail(p_post_id bigint) RETURNS SETOF feed_api.result LANGUAGE sql STABLE
 SET search_path=pg_catalog,feed_data AS $$ SELECT feed_data.post_json(p_post_id) $$;
CREATE FUNCTION public.nhost_create_post(p_body_b64 text,hasura_session json) RETURNS SETOF feed_api.result
 LANGUAGE plpgsql VOLATILE SET search_path=pg_catalog,feed_data AS $$
 DECLARE new_id bigint; actor bigint := (hasura_session->>'x-hasura-user-id')::bigint;
 BEGIN
  INSERT INTO feed_data.posts(user_id,body) VALUES(actor,decode(p_body_b64,'base64')) RETURNING id INTO new_id;
  RETURN QUERY SELECT feed_data.post_json(new_id);
 END
$$;
CREATE FUNCTION public.nhost_like_post(p_post_id bigint,hasura_session json) RETURNS SETOF feed_api.result
 LANGUAGE plpgsql VOLATILE SET search_path=pg_catalog,feed_data AS $$
 DECLARE changed integer; actor bigint := (hasura_session->>'x-hasura-user-id')::bigint;
 BEGIN
  IF NOT EXISTS(SELECT FROM feed_data.posts WHERE id=p_post_id) THEN RETURN QUERY SELECT NULL::jsonb; RETURN; END IF;
  INSERT INTO feed_data.likes(user_id,post_id) VALUES(actor,p_post_id)
   ON CONFLICT(user_id,post_id) DO NOTHING RETURNING 1 INTO changed;
  RETURN QUERY SELECT jsonb_build_object('liked',true,'already_liked',changed IS NULL,'post_id',p_post_id::text);
 END
$$;
REVOKE ALL ON ALL TABLES IN SCHEMA feed_data,feed_api FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA feed_data FROM PUBLIC;
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA feed_data FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.nhost_health(),public.nhost_feed(),public.nhost_detail(bigint),
 public.nhost_create_post(text,json),public.nhost_like_post(bigint,json) FROM PUBLIC;
COMMIT;
