-- Application tables only; Supabase Auth/platform schemas remain untouched.
-- UTF-8 bodies are bytea because PostgreSQL TEXT/JSONB cannot represent U+0000.
-- Native RPC transports base64 bytes; Edge Functions restore the exact JSON string.
BEGIN;
DO $$ BEGIN
 IF NOT EXISTS(SELECT FROM pg_roles WHERE rolname='feed_owner') THEN CREATE ROLE feed_owner NOLOGIN; END IF;
 IF NOT EXISTS(SELECT FROM pg_roles WHERE rolname='feed_reader') THEN CREATE ROLE feed_reader NOLOGIN; END IF;
 IF NOT EXISTS(SELECT FROM pg_roles WHERE rolname='feed_writer') THEN CREATE ROLE feed_writer NOLOGIN; END IF;
END $$;
CREATE SCHEMA IF NOT EXISTS feed_data AUTHORIZATION feed_owner;
CREATE SCHEMA IF NOT EXISTS feed_api AUTHORIZATION feed_owner;
REVOKE ALL ON SCHEMA feed_data,feed_api FROM PUBLIC;
GRANT feed_reader,feed_writer TO authenticator;
SET LOCAL ROLE feed_owner;
ALTER DEFAULT PRIVILEGES IN SCHEMA feed_data,feed_api REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
CREATE OR REPLACE FUNCTION feed_data.codepoints(value bytea) RETURNS bigint
 LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE SET search_path=pg_catalog
 AS $$ SELECT count(*) FROM generate_series(0,octet_length(value)-1) n WHERE (get_byte(value,n)&192)<>128 $$;
CREATE TABLE IF NOT EXISTS feed_data.users (
 id bigint PRIMARY KEY,username text COLLATE "C" NOT NULL UNIQUE,
 created_at text COLLATE "C" NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);
CREATE TABLE IF NOT EXISTS feed_data.posts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES feed_data.users(id),
 body bytea NOT NULL CHECK(feed_data.codepoints(body) BETWEEN 1 AND 500),
 created_at text COLLATE "C" NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);
CREATE TABLE IF NOT EXISTS feed_data.likes (
 user_id bigint NOT NULL REFERENCES feed_data.users(id),post_id bigint NOT NULL REFERENCES feed_data.posts(id),
 created_at text COLLATE "C" NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
 PRIMARY KEY(user_id,post_id)
);
CREATE INDEX IF NOT EXISTS posts_created_at_id_idx ON feed_data.posts(created_at DESC,id DESC);
CREATE INDEX IF NOT EXISTS posts_user_id_idx ON feed_data.posts(user_id);
CREATE INDEX IF NOT EXISTS likes_post_id_idx ON feed_data.likes(post_id);
CREATE OR REPLACE FUNCTION feed_data.post_json(p_id bigint) RETURNS jsonb
 LANGUAGE sql STABLE SET search_path=pg_catalog,feed_data AS $$
 SELECT jsonb_build_object('id',p.id,'body_b64',encode(p.body,'base64'),'created_at',p.created_at,'author',u.username,
 'like_count',(SELECT count(*) FROM feed_data.likes l WHERE l.post_id=p.id))
 FROM feed_data.posts p JOIN feed_data.users u ON u.id=p.user_id WHERE p.id=p_id
 $$;
CREATE OR REPLACE FUNCTION feed_data.writer_id() RETURNS bigint
 LANGUAGE plpgsql STABLE SET search_path=pg_catalog AS $$
 DECLARE value text := nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'app_user_id';
 BEGIN
  IF value IS NULL OR value !~ '^[1-9][0-9]*$' OR length(value)>19 THEN RAISE insufficient_privilege; END IF;
  RETURN value::bigint;
 EXCEPTION WHEN numeric_value_out_of_range OR invalid_text_representation THEN RAISE insufficient_privilege;
 END $$;
CREATE OR REPLACE FUNCTION feed_api.health() RETURNS boolean
 LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,feed_data AS $$
 BEGIN PERFORM 1 FROM feed_data.users LIMIT 1; RETURN true; END $$;
CREATE OR REPLACE FUNCTION feed_api.feed() RETURNS jsonb
 LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,feed_data AS $$
 SELECT coalesce(jsonb_agg(feed_data.post_json(p.id) ORDER BY p.created_at DESC,p.id DESC),'[]'::jsonb)
 FROM (SELECT id,created_at FROM feed_data.posts ORDER BY created_at DESC,id DESC LIMIT 20) p
 $$;
CREATE OR REPLACE FUNCTION feed_api.detail(p_post_id bigint) RETURNS jsonb
 LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,feed_data
 AS $$ SELECT feed_data.post_json(p_post_id) $$;
CREATE OR REPLACE FUNCTION feed_api.create_post(p_body_b64 text) RETURNS jsonb
 LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,feed_data AS $$
 DECLARE post_id bigint;
 BEGIN
  INSERT INTO feed_data.posts(user_id,body) VALUES(feed_data.writer_id(),decode(p_body_b64,'base64')) RETURNING id INTO post_id;
  RETURN feed_data.post_json(post_id);
 END $$;
CREATE OR REPLACE FUNCTION feed_api.like_post(p_post_id bigint) RETURNS jsonb
 LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,feed_data AS $$
 DECLARE changed integer; user_id bigint := feed_data.writer_id();
 BEGIN
  IF NOT EXISTS(SELECT FROM feed_data.posts WHERE id=p_post_id) THEN RETURN NULL; END IF;
  INSERT INTO feed_data.likes(user_id,post_id) VALUES(user_id,p_post_id) ON CONFLICT DO NOTHING RETURNING 1 INTO changed;
  RETURN jsonb_build_object('liked',true,'post_id',p_post_id,'already_liked',changed IS NULL);
 END $$;
REVOKE ALL ON ALL TABLES IN SCHEMA feed_data FROM PUBLIC,feed_reader,feed_writer,anon,authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA feed_data FROM PUBLIC,feed_reader,feed_writer,anon,authenticated;
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA feed_data,feed_api FROM PUBLIC,feed_reader,feed_writer,anon,authenticated;
GRANT USAGE ON SCHEMA feed_api TO feed_reader,feed_writer,anon,authenticated;
GRANT EXECUTE ON FUNCTION feed_api.health(),feed_api.feed(),feed_api.detail(bigint) TO feed_reader,anon,authenticated;
GRANT EXECUTE ON FUNCTION feed_api.create_post(text),feed_api.like_post(bigint) TO feed_writer;
COMMIT;
NOTIFY pgrst,'reload schema';
